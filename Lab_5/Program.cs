using System;
class Program
{
    static void Main()
    {
        string[] verh = { "S", "A1", "B1", "C1", "A2", "B2", "C2", "A3", "B3", "C3", "A4", "B4", "C4", "T" }; // Масив со всеми вершинами
        int[,] matrix = new int[14, 14] // Матрица смежности по графу, 1000 это отсутствие связи
        {
            {0, 10, 9, 12, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000},
            {1000, 1000, 1000, 1000, 12, 7, 6, 1000, 1000, 1000, 1000, 1000, 1000, 1000},
            {1000, 1000, 1000, 1000, 10, 11, 14, 1000, 1000, 1000, 1000, 1000, 1000, 1000},
            {1000, 1000, 1000, 1000, 9, 8, 15, 1000, 1000, 1000, 1000, 1000, 1000, 1000},
            {1000, 1000, 1000, 1000, 1000, 1000, 1000, 7, 14, 9, 1000, 1000, 1000, 1000},
            {1000, 1000, 1000, 1000, 1000, 1000, 1000, 12, 10, 13, 1000, 1000, 1000, 1000},
            {1000, 1000, 1000, 1000, 1000, 1000, 1000, 11, 15, 8, 1000, 1000, 1000, 1000},
            {1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 10, 15, 8, 1000},
            {1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 13, 11, 6, 1000},
            {1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 14, 12, 9, 1000},
            {1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 5 },
            {1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 5 },
            {1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 5 },
            {1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000, 1000},
        };

        int[,] D = new int[14, 3]; // Создаем матрицу для заполнения (вершина, растояние, метка)
        int[] predok = new int[14]; // Масcив для хранения предыдущих точек

        for (int i = 0; i < 14; i++) // Заполняем  матрицу D начальными значениями
        {
            D[i, 0] = i;        // Заполняем индекс вершины
            D[i, 1] = 1000;     // Изначальное растояние до всех выставляем 1000
            D[i, 2] = 0;        // Изначально метка до всех равна 0
            predok[i] = -1;     // Для начала пишем, что ни у кого нет предыдущей
        }
        D[0, 1] = 0; // Изначальное растояние до вершины S = 0

        Console.WriteLine("Матрица смежности:"); // Вывод матрицы смежности
        for (int i = 0; i < 14; i++) // Перебор по строкам
        {
            for (int j = 0; j < 14; j++) // Перебор по столбцам
            {
                Console.Write(matrix[i, j] + "\t"); // Выводим элементы матрицы смежности
            }
            Console.WriteLine(); // Срез в конце каждой строки
        }
        Console.WriteLine(); // Чтоб не слиплось

        int tekushaya = 0; // Начинаем с S

        // Алгоритм Дейкстры
        while (tekushaya != -1) // Пока есть вершины для обработки, продолжаем цикл
        {
            D[tekushaya, 2] = 1; // Помечаем эту точку как обработанную
            Console.Write("Просмотрена вершина "); // Как в примере. Текущая это индекс самой себя в вершине
            Console.WriteLine(verh[tekushaya]);

            for (int j = 0; j < 14; j++) // Делаем перебор по соседним вершинам
            {
                if (matrix[tekushaya, j] != 1000 && D[j, 2] == 0) // Если есть ребро и вершина не обработана
                {
                    int novoe = D[tekushaya, 1] + matrix[tekushaya, j]; // Вычисляем новое растояние
                    if (novoe < D[j, 1]) // Сравниваем со старым растоянием
                    {
                        Console.WriteLine($"от узла {verh[tekushaya]} до узла {verh[j]} новое расстояние={novoe} старое расстояние={D[j, 1]}"); // Как в примере
                        D[j, 1] = novoe; // Перезаписываем новое более короткое растояние
                        predok[j] = tekushaya; // Запоминаем кода пришли от текущей
                    }
                }
            }

            // Ищем следующую необработанную вершину с минимальным расстоянием
            tekushaya = -1; // Сбрасываем значение до изначального
            int minim = 1000; // Сбрасываем минимум до изначального 
            for (int i = 0; i < 14; i++) // Перебираем все вершины
            {
                if (D[i, 2] == 0 && D[i, 1] < minim) // Если она ещё не обработана и растояние до нее меньше минимума
                {
                    minim = D[i, 1]; // Запоминаем новое растояние
                    tekushaya = i; //  Запоминаем новую текущую
                }
            }
            Console.WriteLine(); // Чтобы не слиплось
        }
        Console.WriteLine("Кратчайший путь от S до T:");
        List<string> path = new List<string>();
        int current = 13; // T имеет индекс 13
        while (current != -1)
        {
            path.Insert(0, verh[current]);
            current = predok[current];
        }
        Console.WriteLine(string.Join(" -> ", path));
        Console.WriteLine($"Длина пути: {D[13, 1]}");
        Console.WriteLine();

        Console.WriteLine("Кратчайшие расстояния до вершин:"); // Как в примере
        Console.WriteLine("Вершина Di j Метка"); // Выводим результат, матрица D
        for (int i = 0; i < 14; i++) // Перебираем по всем строкам
        {
                Console.Write(verh[i] + "\t" + D[i, 1] + "\t" + D[i, 2]); // Выводим каждый элемент по отдельности
                Console.WriteLine(); // Делаем срез в конце каждой строки
        }
    }
}